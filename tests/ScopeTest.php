<?php

namespace Oweb\License\Tests;

class ScopeTest extends TestCase
{
	protected function scope(string $namespace, string $target): array
	{
		$command = escapeshellarg(PHP_BINARY) . ' ' .
			escapeshellarg(dirname(__DIR__) . '/bin/scope') . ' ' .
			escapeshellarg($namespace) . ' ' .
			escapeshellarg($target) . ' 2>&1';

		exec($command, $output, $code);

		return [$code, implode("\n", $output)];
	}

	public function testScope(): void
	{
		$target = $this->tmp . '/plugin/lib/license';

		[$code, $output] = $this->scope('Acme\ScopeTest\License', $target);

		$this->assertSame(0, $code, $output);
		$this->assertStringContainsString('(Acme\ScopeTest\License)', $output);
		$this->assertFileExists($target . '/autoload.php');
		$this->assertFileExists($target . '/License.php');
		$this->assertFileExists($target . '/translations/tr.php');

		$code = file_get_contents($target . '/License.php');
		$this->assertStringContainsString('namespace Acme\ScopeTest\License;', $code);
		$this->assertStringNotContainsString('Oweb\License', $code);

		// the copy works next to the original package
		require $target . '/autoload.php';

		$this->app();
		$this->store([]);

		$license = new \Acme\ScopeTest\License\License(
			plugin: 'acme/scope-test',
			products: [100],
			store: static::STORE
		);

		$this->assertSame(\Acme\ScopeTest\License\Status::Active, $license->status());
		$this->assertSame('oweb-license/acme/scope-test', $license->dialog());
		$this->assertSame('Active', \Acme\ScopeTest\License\Translation::get('status.active', locale: 'en'));
	}

	public function testScopeAgainRemovesOldFiles(): void
	{
		$target = $this->tmp . '/lib';

		$this->assertSame(0, $this->scope('Acme\Again\License', $target)[0]);

		touch($target . '/Old.php');

		$this->assertSame(0, $this->scope('Acme\Again\License', $target)[0]);
		$this->assertFileDoesNotExist($target . '/Old.php');
	}

	public function testScopeRefusesForeignDirectory(): void
	{
		$target = $this->tmp . '/src';
		mkdir($target);
		file_put_contents($target . '/Plugin.php', '<?php');

		[$code, $output] = $this->scope('Acme\Foreign\License', $target);

		$this->assertSame(1, $code);
		$this->assertStringContainsString('was not generated by this script', $output);
		$this->assertFileExists($target . '/Plugin.php');
	}

	public function testScopeRefusesInvalidNamespace(): void
	{
		$this->assertSame(1, $this->scope('Acme\1Invalid', $this->tmp . '/lib')[0]);
		$this->assertSame(1, $this->scope('Oweb\License', $this->tmp . '/lib')[0]);
		$this->assertSame(1, $this->scope('', $this->tmp . '/lib')[0]);
	}
}
